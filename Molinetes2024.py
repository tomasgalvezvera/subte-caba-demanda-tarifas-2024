# 1.3 FUNCIÓN QUE LEE UN ARCHIVO Y LO DEJA LIMPIO
def leer_archivo(ruta):
    # --- 1.3.1 Leer el archivo como texto ---
    # utf-8-sig descarta el BOM automáticamente
    try:
        with open(ruta, encoding="utf-8-sig") as f:
            texto = f.read()
    # si la codificación no es utf-8, reintenta con latin-1
    except UnicodeDecodeError:
        with open(ruta, encoding="latin-1") as f:
            texto = f.read()

    # --- 1.3.2 Quitar BOM residual ---
    texto = texto.lstrip("\ufeff").replace("ï»¿", "")

    # --- 1.3.3 Tomar la cabecera (primera línea) ---
    primera = texto.split("\n", 1)[0].strip()

    # --- 1.3.4 Si la línea viene entera entre comillas, sacarlas ---
    if primera.startswith('"'):
        texto = texto.replace('"', '')
        primera = primera.replace('"', '')

    # --- 1.3.5 Detectar el separador ---
    sep = ";" if ";" in primera else ","

    # --- 1.3.6 Parsear con pandas el texto ya limpio ---
    df = pd.read_csv(io.StringIO(texto), sep=sep, index_col=False)

    # --- 1.3.7 Normalizar nombres de columnas (sin comillas/espacios, MAYÚSCULAS) ---
    df.columns = df.columns.str.replace('"', '').str.strip().str.upper()

    # --- 1.3.8 Eliminar columnas fantasma ---
    # separadores sobrantes al final de cada línea generan "UNNAMED: n"
    df = df.loc[:, ~df.columns.str.startswith("UNNAMED")]
    df = df.dropna(axis=1, how="all")   # y cualquier columna totalmente vacía

    return df

